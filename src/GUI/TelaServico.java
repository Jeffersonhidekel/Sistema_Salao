    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
      
if (txtNomeServico.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome do serviço!");
            return;
        }

        if (txtValor.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o valor!");
            return;
        }

        try {
            Servico servico = new Servico();
            
            servico.setNome(txtNomeServico.getText().trim());
            servico.setValor(txtValor.getText().trim());

            ServicoDAO dao = new ServicoDAO();
            dao.inserir(servico);

            JOptionPane.showMessageDialog(this, "Serviço salvo com sucesso!");
            limparCampos();
            
            
            atualizarTabela();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar no banco: " + e.getMessage());
        }

          
    

    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
         
        int linha = jTable1.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um serviço!");
            return;
        }

        int resp = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION
        );

        if (resp == JOptionPane.YES_OPTION) {
            try {
                
                long id = Long.parseLong(modelo.getValueAt(linha, 0).toString());

                
                ServicoDAO dao = new ServicoDAO();
                dao.excluir(id);

                
                modelo.removeRow(linha);
                limparCampos();
                jTable1.clearSelection();
                
                JOptionPane.showMessageDialog(this, "Serviço excluído com sucesso!");

                atualizarTabela();
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro ao excluir no banco: " + e.getMessage());
            }
        }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

