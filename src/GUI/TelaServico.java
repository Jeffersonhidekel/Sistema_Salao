    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed

        int linha = jTable1.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um serviço!");
            return;
        }

        try {
            
            long id = Long.parseLong(modelo.getValueAt(linha, 0).toString());

            
            Servico servico = new Servico();
            servico.setId(id);
            servico.setNome(txtNomeServico.getText().trim());
            servico.setValor(txtValor.getText().trim());

            
            ServicoDAO dao = new ServicoDAO();
            dao.atualizar(servico);

            
            modelo.setValueAt(servico.getNome(), linha, 1);
            modelo.setValueAt(servico.getValor(), linha, 2);

            JOptionPane.showMessageDialog(this, "Serviço alterado com sucesso!");

            limparCampos();
            jTable1.clearSelection();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao alterar no banco: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnAlterarActionPerformed

