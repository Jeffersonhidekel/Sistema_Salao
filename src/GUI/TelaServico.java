    private void carregarDadosTabela() {

        int linha = jTable1.getSelectedRow();

        if (linha != -1) {
            txtID.setText(modelo.getValueAt(linha, 0).toString());
            txtNomeServico.setText(modelo.getValueAt(linha, 1).toString());
            txtValor.setText(modelo.getValueAt(linha, 2).toString());
        }
    }
    private void limparCampos() {
        txtID.setText("");
        txtNomeServico.setText("");
        txtValor.setText("");
        txtNomeServico.requestFocus();
    }
    
    private void atualizarTabela() {
        modelo.setRowCount(0); 
        try {
            ServicoDAO dao = new ServicoDAO();
           
            for (Servico servico : dao.listar()) {
                modelo.addRow(new Object[]{
                    servico.getId(),
                    servico.getNome(),
                    servico.getValor()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar serviços: " + e.getMessage());
        }
    }
    
