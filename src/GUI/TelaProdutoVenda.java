    private void carregarDadosTabela() {
    int linha = jTable1.getSelectedRow();

    if (linha != -1) {
        txtCodigo.setText(modelo.getValueAt(linha, 0).toString());
        txtNomeProduto.setText(modelo.getValueAt(linha, 1).toString());
        txtValorCompra.setText(modelo.getValueAt(linha, 2).toString());
        txtValorVenda.setText(modelo.getValueAt(linha, 3).toString());
    }
    
    }
    
    
    private void preencherTabela() {
        ProdutoVendaDAO dao = new ProdutoVendaDAO();
        java.util.List<ProdutoVenda> lista = dao.listar();
        
        modelo.setNumRows(0); 
        
        for (ProdutoVenda p : lista) {
            modelo.addRow(new Object[]{
                p.getCodigoProduto(),
                p.getNome(),
                p.getValorcompra(),
                p.getValorvenda()
            });
        }
    }
    
