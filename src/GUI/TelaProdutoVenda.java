    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
                                                   
    
    if (txtNomeProduto.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o nome do produto!");
        return;
    }
    if (txtValorCompra.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o valor de compra!");
        return;
    }
    if (txtValorVenda.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o valor de venda!");
        return;
    }
   
    if (!validarValores()){  
        return;
    }

   
    try {
        ProdutoVenda ProdutoVenda = new ProdutoVenda();
        
        
        
        ProdutoVenda.setNome(txtNomeProduto.getText().trim());        
    ProdutoVenda.setValorcompra(txtValorCompra.getText().trim());
    ProdutoVenda.setValorvenda(txtValorVenda.getText().trim());

        ProdutoVendaDAO dao = new ProdutoVendaDAO();
        dao.inserir(ProdutoVenda); 
 

        JOptionPane.showMessageDialog(this, "Produto salvo com sucesso!");
        limparCampos();
        
        preencherTabela();

    } catch (Exception e) {
        
        JOptionPane.showMessageDialog(this, "Erro ao salvar no banco: " + e.getMessage());
    }
}                                         

private boolean validarValores() {
    try {
        Double.valueOf(txtValorCompra.getText().replace(",", "."));
        Double.valueOf(txtValorVenda.getText().replace(",", "."));
        return true;
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Informe valores numéricos válidos!");
        return false;
    }
   
    
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
          
int linha = jTable1.getSelectedRow();

    if (linha == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto!");
        return;
    }
  
    if (txtNomeProduto.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o nome do produto!");
        return;
    }
  
    if (txtValorCompra.getText().trim().isEmpty()){
        JOptionPane.showMessageDialog(this, "Informe o valor de compra!");
        return;
    }
    
    if (txtValorVenda.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o valor de venda!");
        return;
    
    }
    
    if (!validarValores()){
        return;
    }
    
    
    try {
       
        String codigoString = modelo.getValueAt(linha, 0).toString();
        long codigo = Long.parseLong(codigoString);

       
        ProdutoVenda produtoVenda = new ProdutoVenda();
        produtoVenda.setCodigoProduto(codigo); 
        produtoVenda.setNome(txtNomeProduto.getText().trim());
        produtoVenda.setValorcompra(txtValorCompra.getText().trim());
        produtoVenda.setValorvenda(txtValorVenda.getText().trim());

        ProdutoVendaDAO dao = new ProdutoVendaDAO();
        dao.atualizar(produtoVenda); 

       
        modelo.setValueAt(txtNomeProduto.getText().trim(), linha, 1);
        modelo.setValueAt(txtValorCompra.getText().trim(), linha, 2);
        modelo.setValueAt(txtValorVenda.getText().trim(), linha, 3);

        JOptionPane.showMessageDialog(this, "Produto alterado com sucesso no banco e na tela!");
        
        limparCampos();
        jTable1.clearSelection();

    } catch (Exception e) {
        
        JOptionPane.showMessageDialog(this, "Erro ao alterar no banco: " + e.getMessage());
    }
    
    
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
           
int linha = jTable1.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um produto!");
            return;
        }

        int resp = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION
        );

        if (resp == JOptionPane.YES_OPTION) {
            try {
                
                String codigoString = modelo.getValueAt(linha, 0).toString();
                long codigo = Long.parseLong(codigoString);

              
                ProdutoVendaDAO dao = new ProdutoVendaDAO();
                dao.excluir(codigo); 

                
                limparCampos();

                
                preencherTabela();

                JOptionPane.showMessageDialog(this, "Produto excluído com sucesso do banco e da tela!");

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro ao excluir no banco: " + e.getMessage());
            }
        }
       
    
        
    
    }//GEN-LAST:event_btnExcluirActionPerformed

